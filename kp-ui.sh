#!/bin/sh
# ============================================================================
#  kp-ui.sh —— 鲲鹏脚本套件共用的「终端界面库」
#
#  这个文件里只有「打印」，没有任何业务逻辑。
#  想换配色、符号、版式，改这一个文件，三个脚本同时生效。
#
#  ── 三条设计约束（都是实测踩出来的）──────────────────────────────
#   1. 只用 busybox sh + printf。路由器上没有 tput，也不保证能装 bash 数组，
#      所以全部用最朴素的 while 循环和 printf 实现。
#   2. 中文在终端占 2 列，但 ${#s} 按字节算 —— 两者不一致。
#      因此版式一律左对齐，绝不做「右边框 / 右对齐」，否则中文一多就歪。
#   3. 输出被重定向到文件时（日志、管道）自动关掉颜色，
#      免得日志里全是 \033 乱码。UI_COLOR=always / never 可强制。
#
#  ── 用法 ──────────────────────────────────────────────────────────
#   . kp-ui.sh
#   ui_init "标题" "副标题"
#   ui_meta 设备 "C2000 Max · aarch64"
#   ui_hr
#   ui_stage 1 5 "环境预检"        # 自动打进度条 + 开始计时
#     ui_ok   "源已切换"
#     ui_warn "veth 未装"
#   ui_stage_end                   # 自动打本阶段耗时
#   ui_done                        # 收尾（后面接几行 ui_kv）
#   ui_kv 面板 "http://192.168.66.1:10090/xxxx"
#   ui_hr2
#
#   失败退出用一行搞定：  ui_fail "原因" "怎么办"
#   完整效果预览：        UI_COLOR=always sh kp-ui-preview.sh
# ============================================================================

# ============================== 配色 ==============================
case "${UI_COLOR:-auto}" in
  always) _uic=1 ;;
  never)  _uic=0 ;;
  *)      if [ -t 1 ]; then _uic=1; else _uic=0; fi ;;
esac
if [ "$_uic" = 1 ]; then
  C='\033[36m'    # 青 —— 主色：标题、阶段号、进度条
  B='\033[1m'     # 粗 —— 强调
  D='\033[2m'     # 灰 —— 次要信息、说明
  G='\033[32m'    # 绿 —— 成功
  Y='\033[33m'    # 黄 —— 警告
  R='\033[31m'    # 红 —— 失败
  Z='\033[0m'     # 复位
else
  C=; B=; D=; G=; Y=; R=; Z=
fi

# ============================== 内部状态 ==============================
UI_W=${UI_W:-56}          # 分隔线宽度（列）。终端窄就把这个值调小
UI_T0=$(date +%s)         # 脚本起始时间，ui_done 用它算总耗时
_ui_t0=0                  # 当前阶段的起始时间

# ============================== 底料 ==============================
# 铺满一行：_rep '─' "$D"
_rep() {
  printf "$2"
  n=$UI_W
  while [ "$n" -gt 0 ]; do printf '%s' "$1"; n=$((n - 1)); done
  printf "$Z\n"
}

ui_hr()  { _rep '─' "$D"; }     # 细线：段落分隔
ui_hr2() { _rep '═' "$G"; }     # 粗线：整体收尾

# 秒 → 45s / 1m23s
ui_hms() {
  if [ "$1" -lt 60 ]; then printf '%ss' "$1"
  else printf '%dm%02ds' "$(( $1 / 60 ))" "$(( $1 % 60 ))"; fi
}

# ============================== 头部 ==============================
# ui_init "主标题" "副标题"
ui_init() {
  printf '\n'
  ui_hr
  printf "  $B$C%s$Z\n" "$1"
  [ -n "${2:-}" ] && printf "  $D%s$Z\n" "$2"
  ui_hr
}

# ui_meta 标签 值 —— 标签统一写 2 个汉字，才能上下对齐
ui_meta() { printf "  $D%s$Z  %s\n" "$1" "$2"; }

# ============================== 阶段 ==============================
# ui_stage 序号 总数 "标题"
ui_stage() {
  _ui_t0=$(date +%s)
  printf "\n$B$C[%s/%s]$Z $B%s$Z  " "$1" "$2" "$3"
  ui_bar "$1" "$2"
  printf '\n'
}

# 本阶段耗时
ui_stage_end() { printf "  $D↳ %s$Z\n" "$(ui_hms $(( $(date +%s) - _ui_t0 )))"; }

# 进度条：ui_bar 2 5 → ████████░░░░░░░░░░░░
ui_bar() {
  n=20
  f=$(( n * $1 / $2 ))
  printf "$C"
  i=0; while [ "$i" -lt "$f" ]; do printf '█'; i=$((i + 1)); done
  printf "$D"
  i=$f; while [ "$i" -lt "$n" ]; do printf '░'; i=$((i + 1)); done
  printf "$Z"
}

# ============================== 条目 ==============================
ui_ok()   { printf "  $G✓$Z %s\n" "$*"; }        # 成功 / 已完成
ui_info() { printf "  $D·$Z %s\n" "$*"; }        # 中性进度提示
ui_warn() { printf "  $Y!$Z %s\n" "$*"; }        # 警告：不中断
ui_err()  { printf "  $R✗$Z %s\n" "$*" >&2; }    # 错误：不退出，由调用方决定
ui_note() { printf "    $D%s$Z\n" "$*"; }        # 条目下的补充说明
ui_kv()   { printf "  $D%s$Z  %s\n" "$1" "$2"; } # 键值对（汇总区用）

# 空白行（需要视觉留白时用）
ui_gap()  { printf '\n'; }

# ============================== 收尾 ==============================
# 失败并退出：ui_fail "原因" "怎么办（可省略）"
ui_fail() {
  printf "\n  $R$B✗ %s$Z\n" "$1" >&2
  [ -n "${2:-}" ] && printf "    $D→ %s$Z\n" "$2" >&2
  printf "  $D脚本已停止。修好后重跑即可 —— 本套件幂等，不会重复安装。$Z\n\n" >&2
  exit 1
}

# 成功收尾的头：后面接几行 ui_kv，最后 ui_hr2 封口
ui_done() {
  printf '\n'
  printf "  $B$G✓ 全部完成$Z   $D总用时 %s$Z\n" "$(ui_hms $(( $(date +%s) - UI_T0 )))"
  ui_hr
}
